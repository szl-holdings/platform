function trustScore(
  accuracy: number,
  approval: number,
  cost: number,
  uptime: number,
  proof: number,
): TrustScore {
  const overall = Math.round((accuracy + approval + cost + uptime + proof) / 5);
  let tier: TrustTier = 'untrusted';
  if (overall >= 95) tier = 'sovereign';
  else if (overall >= 80) tier = 'elevated';
  else if (overall >= 60) tier = 'standard';
  else if (overall >= 40) tier = 'provisional';
  return {
    overall,
    rollingAccuracy: accuracy,
    approvalRate: approval,
    costEfficiency: cost,
    uptimeReliability: uptime,
    proofCompleteness: proof,
    tier,
    computedAt: new Date(Date.now() - 120_000).toISOString(),
    historyWindow: 168,
  };
}

