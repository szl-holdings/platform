export function computeMeshSummary(agents: FieldAgent[], crews: CrewComposition[]): MeshSummary {
  const activeAgents = agents.filter(a => a.status === 'active').length;
  const activeCrews = crews.filter(c => c.status === 'active').length;
  const totalProofs = agents.reduce((s, a) => s + a.proofPacketIds.length, 0);
  const avgTrust = agents.length > 0
    ? Math.round(agents.reduce((s, a) => s + a.trustScore.overall, 0) / agents.length)
    : 0;
  const totalCost = agents.reduce((s, a) => s + a.totalCostUsd, 0);
  return {
    totalAgents: agents.length,
    activeAgents,
    totalCrews: crews.length,
    activeCrews,
    totalMessages: AGENT_MESSAGES.length,
    totalProofPackets: totalProofs,
    avgTrustScore: avgTrust,
    totalCostUsd: Math.round(totalCost * 100) / 100,
    uptimePercent: 99.7,
  };
}
