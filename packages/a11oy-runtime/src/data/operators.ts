function score(g: number, ev: number, ap: number, lh: number, sv: number, lr: number) {
  const overall = Math.round((g + ev + ap + lh + sv + lr) / 6);
  return {
    overall,
    groundedness: g,
    evidenceCoverage: ev,
    approvalCorrectness: ap,
    lowHallucinationScore: lh,
    successfulVerification: sv,
    lowRollbackRate: lr,
    computedAt: new Date(Date.now() - 3600_000).toISOString(),
  };
}

