export function getCompatibility(a: string, b: string): CompatibilityEntry {
  const entry = COMPATIBILITY[a]?.[b] || COMPATIBILITY[b]?.[a];
  if (entry) return entry;
  return { status: 'unknown', note: 'Compatibility not assessed for this pair.' };
}

export function getCompatibilityColor(status: CompatibilityStatus): string {
  switch (status) {
    case 'compatible': return '#34d399';
    case 'incompatible': return '#f87171';
    case 'partial': return '#fbbf24';
    default: return '#64748b';
  }
}

export function getCompatibilityBgClass(status: CompatibilityStatus): string {
  switch (status) {
    case 'compatible': return 'compat-green';
    case 'incompatible': return 'compat-red';
    case 'partial': return 'compat-amber';
    default: return 'compat-gray';
  }
}
