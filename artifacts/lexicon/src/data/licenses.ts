// Helper functions
export function getLicenseById(id: string): License | undefined {
  return LICENSES.find((l) => l.id === id);
}

export function getLicensesByCategory(category: LicenseCategory): License[] {
  return LICENSES.filter((l) => l.category === category);
}

export function getLicensesByFamily(family: LicenseFamily): License[] {
  return LICENSES.filter((l) => l.family === family);
}

export function searchLicenses(query: string): License[] {
  const q = query.toLowerCase().trim();
  if (!q) return LICENSES;
  return LICENSES.filter(
    (l) =>
      l.id.toLowerCase().includes(q) ||
      l.name.toLowerCase().includes(q) ||
      (l.shortName?.toLowerCase().includes(q)) ||
      (l.spdxId?.toLowerCase().includes(q)) ||
      l.summary.toLowerCase().includes(q) ||
      l.tags.some((t) => t.includes(q)) ||
      l.family.toLowerCase().includes(q) ||
      l.category.toLowerCase().includes(q),
  );
}

