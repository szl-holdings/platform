type AudioBriefState = 'idle' | 'loading' | 'playing' | 'error';

function getAudioApiBase() {
  const base = import.meta.env.BASE_URL?.replace(/\/$/, '') || '';
  return `${base}/api`;
}

export default function TodaysBrief() {
  const { data: brief, isLoading, error } = useTodaysBrief();
  const generate = useGenerateBriefing();
  const [exporting, setExporting] = useState(false);
  const [generateError, setGenerateError] = useState<string | null>(null);
  const [, navigate] = useLocation();

  const [audioBriefState, setAudioBriefState] = useState<AudioBriefState>('idle');
  const [audioDownloadUrl, setAudioDownloadUrl] = useState<string | null>(null);
  const [audioProvenance, setAudioProvenance] = useState<{
    model: string; voice: string; format: string; generatedAt: string; briefId?: string; source?: string;
  } | null>(null);
  const audioBriefRef = useRef<HTMLAudioElement | null>(null);
  const audioObjectUrlRef = useRef<string | null>(null);
  const audioAbortRef = useRef<AbortController | null>(null);

  const handleListen = useCallback(async () => {
    if (!brief) return;
    if (audioBriefState === 'playing') {
      audioAbortRef.current?.abort();
      audioBriefRef.current?.pause();
      if (audioObjectUrlRef.current) {
        URL.revokeObjectURL(audioObjectUrlRef.current);
        audioObjectUrlRef.current = null;
      }
      setAudioBriefState('idle');
      return;
    }

    audioAbortRef.current?.abort();
    const abort = new AbortController();
    audioAbortRef.current = abort;

    setAudioBriefState('loading');

    const parts: string[] = [];
    parts.push(`Executive Briefing — ${brief.date}. Edition: ${brief.edition}.`);
    parts.push(brief.headline);
    if (brief.leadSentence) parts.push(brief.leadSentence);
    if (brief.recommendedActions?.length) {
      const actionSummaries = brief.recommendedActions
        .map((a) => `[${a.priority}] ${a.action}`)
        .join('. ');
      parts.push('Recommended actions: ' + actionSummaries);
    }

    try {
      const res = await fetch(`${getAudioApiBase()}/openai/briefing-audio`, {
        method: 'POST',
        headers: { 'Content-Type': 'application/json' },
        body: JSON.stringify({
          text: parts.join('\n\n'),
          briefId: brief.id,
          voice: 'nova',
        }),
        credentials: 'include',
        signal: abort.signal,
      });

      if (!res.ok) throw new Error('Audio generation failed');

      const data = await res.json() as {
        audioBase64: string;
        mimeType: string;
        provenance?: { model: string; voice: string; format: string; generatedAt: string; briefId?: string };
        source?: string;
      };
      if (abort.signal.aborted) return;

      if (data.provenance) {
        setAudioProvenance({ ...data.provenance, source: data.source });
      }

      const binaryStr = atob(data.audioBase64);
      const bytes = new Uint8Array(binaryStr.length);
      for (let i = 0; i < binaryStr.length; i++) bytes[i] = binaryStr.charCodeAt(i);
      const blob = new Blob([bytes], { type: data.mimeType || 'audio/mpeg' });

      // Create a persistent download URL (separate from the playback URL)
      const downloadUrl = URL.createObjectURL(blob);
      setAudioDownloadUrl((prev) => {
        if (prev) URL.revokeObjectURL(prev);
        return downloadUrl;
      });

      const url = URL.createObjectURL(blob);
      audioObjectUrlRef.current = url;

      const audio = new Audio(url);
      audioBriefRef.current = audio;
      setAudioBriefState('playing');

      audio.onended = () => {
        setAudioBriefState('idle');
        URL.revokeObjectURL(url);
        audioObjectUrlRef.current = null;
      };
      audio.onerror = () => setAudioBriefState('error');
      abort.signal.addEventListener('abort', () => {
        audio.pause();
      });
      audio.play().catch(() => setAudioBriefState('error'));
    } catch (err) {
      if ((err as Error).name === 'AbortError') {
        setAudioBriefState('idle');
        return;
      }
      setAudioBriefState('error');
    }
  }, [brief, audioBriefState]);

  const handleGenerate = async () => {
    setGenerateError(null);
    try {
      await generate.mutateAsync();
    } catch (e) {
      setGenerateError(e instanceof Error ? e.message : String(e));
    }
  };
  const handleExport = async () => {
    if (!brief) return;
    setExporting(true);
    try {
      await exportBriefingPdf(brief.id, brief.date);
    } catch (e) {
      alert(`PDF export failed: ${e instanceof Error ? e.message : String(e)}`);
    } finally {
      setExporting(false);
    }
  };

  const handleFileDissent = (sectionTitle: string) => {
    navigate(`${BASE}/dissent?section=${encodeURIComponent(sectionTitle)}`);
  };

  if (isLoading) {
    return <BriefSkeleton />;
  }
  if (error || !brief) {
    return (
      <div
        role="alert"
        style={{
          padding: '32px 28px',
          display: 'flex',
          flexDirection: 'column',
          gap: 12,
        }}
      >
        <div
          style={{
            display: 'flex',
            alignItems: 'center',
            gap: 8,
            padding: '14px 18px',
            borderRadius: 6,
            background: 'rgba(224,80,80,0.06)',
            border: '1px solid rgba(224,80,80,0.2)',
          }}
        >
          <AlertTriangle size={16} color="#e05050" />
          <div>
            <div style={{ fontSize: '0.8rem', fontWeight: 600, color: '#e05050', marginBottom: 2 }}>
              Failed to load today&apos;s brief
            </div>
            <div style={{ fontSize: '0.75rem', color: 'var(--pulse-text-muted)' }}>
              {error instanceof Error ? error.message : 'Unknown error'}
            </div>
          </div>
        </div>
        {!isDemoMode() && (
          <button
            type="button"
            onClick={handleGenerate}
            disabled={generate.isPending}
            style={{
              alignSelf: 'flex-start',
              display: 'flex',
              alignItems: 'center',
              gap: 6,
              padding: '8px 14px',
              borderRadius: 6,
              background: 'rgba(120,180,255,0.10)',
              border: '1px solid rgba(120,180,255,0.35)',
              color: '#9bc4ff',
              fontSize: '0.78rem',
              fontWeight: 600,
              cursor: generate.isPending ? 'wait' : 'pointer',
            }}
          >
            <Sparkles size={13} />
            {generate.isPending ? 'Generating…' : 'Generate Now'}
          </button>
        )}
      </div>
    );
  }

  return (
    <div style={{ padding: '0 0 40px' }}>
      {/* Brief header */}
      <div
        style={{
          padding: '28px 28px 20px',
          borderBottom: '1px solid var(--pulse-border)',
          background: 'linear-gradient(180deg, rgba(200,168,75,0.04) 0%, transparent 100%)',
        }}
      >
        <div
          style={{
            display: 'flex',
            alignItems: 'flex-start',
            justifyContent: 'space-between',
            marginBottom: 16,
          }}
        >
          <div>
            <div style={{ display: 'flex', alignItems: 'center', gap: 8, marginBottom: 8, flexWrap: 'wrap' }}>
              <div
                className="font-mono"
                style={{
                  fontSize: '0.65rem',
                  color: 'var(--pulse-gold)',
                  fontWeight: 600,
                  letterSpacing: '0.1em',
                  textTransform: 'uppercase',
                }}
              >
                {brief.edition}
              </div>
              <div
                style={{
                  width: 4,
                  height: 4,
                  borderRadius: '50%',
                  background: 'var(--pulse-border-bright)',
                  flexShrink: 0,
                }}
              />
              <div
                className="font-mono"
                style={{
                  fontSize: '0.65rem',
                  color: 'var(--pulse-text-muted)',
                  letterSpacing: '0.05em',
                }}
              >
                {new Date(brief.date).toLocaleDateString('en-US', {
                  weekday: 'long',
                  year: 'numeric',
                  month: 'long',
                  day: 'numeric',
                })}
              </div>
              <div
                style={{
                  width: 4,
                  height: 4,
                  borderRadius: '50%',
                  background: 'var(--pulse-border-bright)',
                  flexShrink: 0,
                }}
              />
              <FreshnessChip generatedAt={brief.generatedAt} />
              <ProvenanceBadge edition={brief.edition} />
              {isDemoMode() && (
                <div
                  className="font-mono"
                  title="Viewing demo data — sign in for live briefings."
                  style={{
                    fontSize: '0.62rem',
                    color: 'var(--pulse-gold)',
                    fontWeight: 600,
                    letterSpacing: '0.08em',
                    padding: '1px 6px',
                    border: '1px solid var(--pulse-border-bright)',
                    borderRadius: 3,
                  }}
                >
                  DEMO
                </div>
              )}
            </div>
            <h1
              className="font-serif"
              style={{
                fontSize: '1.6rem',
                fontWeight: 500,
                color: 'var(--pulse-text)',
                lineHeight: 1.35,
                maxWidth: 700,
                marginBottom: 10,
              }}
            >
              {brief.headline}
            </h1>
            <p
              className="font-serif"
              style={{
                fontSize: '1rem',
                color: 'var(--pulse-text-dim)',
                lineHeight: 1.6,
                maxWidth: 640,
              }}
            >
              {brief.leadSentence}
            </p>
          </div>
          <div
            style={{
              display: 'flex',
              flexDirection: 'column',
              gap: 8,
              alignItems: 'flex-end',
              flexShrink: 0,
              marginLeft: 24,
            }}
          >
            <div style={{ display: 'flex', gap: 8 }}>
              <RiskBadge risk={brief.overallRisk} />
              <ConfidenceChip score={brief.overallConfidence} />
            </div>
            <div style={{ display: 'flex', gap: 6 }}>
              {!isDemoMode() && (
                <button
                  type="button"
                  onClick={handleGenerate}
                  disabled={generate.isPending}
                  title="Synthesize a fresh briefing from the agent collective"
                  style={{
                    display: 'flex',
                    alignItems: 'center',
                    gap: 6,
                    padding: '8px 14px',
                    borderRadius: 6,
                    background: 'rgba(120,180,255,0.10)',
                    border: '1px solid rgba(120,180,255,0.35)',
                    color: '#9bc4ff',
                    fontSize: '0.78rem',
                    fontWeight: 600,
                    cursor: generate.isPending ? 'wait' : 'pointer',
                  }}
                >
                  <Sparkles size={13} />
                  {generate.isPending ? 'Generating…' : 'Generate Live Briefing'}
                </button>
              )}
              <button
                type="button"
                onClick={handleListen}
                disabled={audioBriefState === 'loading'}
                title={audioBriefState === 'playing' ? 'Stop audio briefing' : 'Listen to this briefing via AI voice'}
                style={{
                  display: 'flex',
                  alignItems: 'center',
                  gap: 6,
                  padding: '8px 14px',
                  borderRadius: 6,
                  background: audioBriefState === 'playing'
                    ? 'rgba(120,180,255,0.18)'
                    : audioBriefState === 'error'
                    ? 'rgba(224,80,80,0.10)'
                    : 'rgba(120,180,255,0.08)',
                  border: audioBriefState === 'playing'
                    ? '1px solid rgba(120,180,255,0.55)'
                    : audioBriefState === 'error'
                    ? '1px solid rgba(224,80,80,0.40)'
                    : '1px solid rgba(120,180,255,0.28)',
                  color: audioBriefState === 'error' ? '#e05050' : '#9bc4ff',
                  fontSize: '0.78rem',
                  fontWeight: 600,
                  cursor: audioBriefState === 'loading' ? 'wait' : 'pointer',
                }}
              >
                {audioBriefState === 'loading' && <Loader2 size={13} style={{ animation: 'spin 1s linear infinite' }} />}
                {audioBriefState === 'playing' && <Square size={13} />}
                {audioBriefState === 'idle' && <Volume2 size={13} />}
                {audioBriefState === 'error' && <VolumeX size={13} />}
                {audioBriefState === 'loading' ? 'Generating…' : audioBriefState === 'playing' ? 'Stop' : audioBriefState === 'error' ? 'Retry Audio' : 'Listen'}
              </button>
              {audioDownloadUrl && (
                <a
                  href={audioDownloadUrl}
                  download={`briefing-${brief?.id ?? 'audio'}.mp3`}
                  title="Download this briefing as an MP3 audio file"
                  style={{
                    display: 'flex',
                    alignItems: 'center',
                    gap: 6,
                    padding: '8px 14px',
                    borderRadius: 6,
                    background: 'rgba(120,180,255,0.06)',
                    border: '1px solid rgba(120,180,255,0.22)',
                    color: '#9bc4ff',
                    fontSize: '0.78rem',
                    fontWeight: 600,
                    textDecoration: 'none',
                    cursor: 'pointer',
                  }}
                >
                  <Download size={13} />
                  MP3
                </a>
              )}
              <button
                type="button"
                onClick={handleExport}
                disabled={exporting}
                title="Download a branded PDF of this briefing"
                style={{
                  display: 'flex',
                  alignItems: 'center',
                  gap: 6,
                  padding: '8px 14px',
                  borderRadius: 6,
                  background: 'rgba(200,168,75,0.10)',
                  border: '1px solid rgba(200,168,75,0.45)',
                  color: 'var(--pulse-gold)',
                  fontSize: '0.78rem',
                  fontWeight: 600,
                  cursor: exporting ? 'wait' : 'pointer',
                }}
              >
                <Download size={13} />
                {exporting ? 'Preparing PDF…' : 'Export PDF'}
              </button>
            </div>
            {/* Provenance envelope — shown after audio is generated */}
            {audioProvenance && (
              <div style={{
                display: 'flex',
                alignItems: 'center',
                gap: 8,
                marginTop: 8,
                padding: '5px 10px',
                borderRadius: 6,
                background: 'rgba(255,255,255,0.03)',
                border: '1px solid rgba(255,255,255,0.07)',
                width: 'fit-content',
              }}>
                <span style={{ fontSize: '0.68rem', color: 'rgba(255,255,255,0.35)', letterSpacing: '0.04em' }}>
                  AUDIO PROVENANCE
                </span>
                <span style={{ fontSize: '0.68rem', color: 'rgba(255,255,255,0.5)' }}>
                  {audioProvenance.model} · {audioProvenance.voice} · {audioProvenance.format.toUpperCase()}
                </span>
                {audioProvenance.source === 'cache' && (
                  <span style={{ fontSize: '0.65rem', color: 'rgba(120,200,100,0.7)', fontWeight: 600 }}>CACHED</span>
                )}
                <span style={{ fontSize: '0.65rem', color: 'rgba(255,255,255,0.25)' }}>
                  {new Date(audioProvenance.generatedAt).toLocaleTimeString()}
                </span>
              </div>
            )}
          </div>
        </div>

        {/* Domain pills */}
        <div style={{ display: 'flex', gap: 6, flexWrap: 'wrap' }}>
          {brief.domains.map((d) => (
            <span
              key={d}
              style={{
                padding: '3px 10px',
                borderRadius: 20,
                background: 'var(--pulse-card)',
                border: '1px solid var(--pulse-border)',
                fontSize: '0.68rem',
                color: 'var(--pulse-text-dim)',
                fontWeight: 500,
                textTransform: 'capitalize',
              }}
            >
              {d.replace('_', ' ')}
            </span>
          ))}
        </div>
      </div>

      {/* Content */}
      <div style={{ padding: '24px 28px' }}>
        {/* Generate error banner */}
        {generateError && (
          <div
            role="alert"
            style={{
              display: 'flex',
              alignItems: 'flex-start',
              gap: 10,
              padding: '10px 14px',
              borderRadius: 6,
              background: 'rgba(224,80,80,0.06)',
              border: '1px solid rgba(224,80,80,0.2)',
              marginBottom: 16,
            }}
          >
            <AlertTriangle size={14} color="#e05050" style={{ marginTop: 1, flexShrink: 0 }} />
            <div>
              <div style={{ fontSize: '0.78rem', fontWeight: 600, color: '#e05050', marginBottom: 2 }}>
                Live generation failed
              </div>
              <div style={{ fontSize: '0.72rem', color: 'var(--pulse-text-muted)' }}>
                {generateError}
              </div>
            </div>
            <button
              type="button"
              onClick={() => setGenerateError(null)}
              style={{ background: 'none', border: 'none', cursor: 'pointer', color: 'var(--pulse-text-muted)', padding: 2, marginLeft: 'auto', flexShrink: 0 }}
              aria-label="Dismiss"
            >
              ×
            </button>
          </div>
        )}
        {/* Recommended Actions */}
        <div style={{ marginBottom: 28 }}>
          <div style={{ display: 'flex', alignItems: 'center', gap: 8, marginBottom: 14 }}>
            <Zap size={14} color="var(--pulse-gold)" />
            <h2
              style={{
                fontSize: '0.7rem',
                fontWeight: 700,
                letterSpacing: '0.1em',
                textTransform: 'uppercase',
                color: 'var(--pulse-text-muted)',
              }}
            >
              Recommended Actions — Today
            </h2>
          </div>
          <div style={{ display: 'flex', flexDirection: 'column', gap: 8 }}>
            {brief.recommendedActions.map((action, i) => {
              const pColor =
                action.priority === 'P0'
                  ? '#e05050'
                  : action.priority === 'P1'
                    ? '#e08c40'
                    : action.priority === 'P2'
                      ? '#c8a84b'
                      : '#4eca8b';
              return (
                <div
                  key={i}
                  style={{
                    display: 'flex',
                    gap: 14,
                    alignItems: 'flex-start',
                    padding: '12px 16px',
                    borderRadius: 6,
                    background: 'var(--pulse-card)',
                    border: `1px solid ${pColor}25`,
                    borderLeft: `3px solid ${pColor}`,
                  }}
                >
                  <span
                    style={{
                      fontWeight: 800,
                      fontSize: '0.65rem',
                      color: pColor,
                      background: `${pColor}18`,
                      padding: '2px 6px',
                      borderRadius: 3,
                      fontFamily: 'JetBrains Mono, monospace',
                      flexShrink: 0,
                    }}
                  >
                    {action.priority}
                  </span>
                  <div style={{ flex: 1 }}>
                    <div
                      style={{
                        fontSize: '0.88rem',
                        fontWeight: 500,
                        color: 'var(--pulse-text)',
                        marginBottom: 3,
                      }}
                    >
                      {action.action}
                    </div>
                    <div
                      style={{
                        fontSize: '0.75rem',
                        color: 'var(--pulse-text-dim)',
                        lineHeight: 1.5,
                      }}
                    >
                      {action.rationale}
                    </div>
                    <div
                      style={{
                        display: 'flex',
                        gap: 12,
                        marginTop: 6,
                        fontSize: '0.7rem',
                        color: 'var(--pulse-text-muted)',
                      }}
                    >
                      <span>Owner: {action.owner}</span>
                      <span>·</span>
                      <span>Due: {action.dueBy}</span>
                    </div>
                  </div>
                </div>
              );
            })}
          </div>
        </div>

        {/* Agent Mesh Status */}
        <div style={{ marginBottom: 28 }}>
          <div style={{ display: 'flex', alignItems: 'center', gap: 8, marginBottom: 14 }}>
            <Shield size={14} color="#e05050" />
            <h2
              style={{
                fontSize: '0.7rem',
                fontWeight: 700,
                letterSpacing: '0.1em',
                textTransform: 'uppercase',
                color: 'var(--pulse-text-muted)',
              }}
            >
              Agent Mesh · AI Supply Chain Status
            </h2>
          </div>
          <MeshCard />
        </div>

        {/* Domain sections */}
        <div style={{ marginBottom: 12 }}>
          <div style={{ display: 'flex', alignItems: 'center', gap: 8, marginBottom: 14 }}>
            <Shield size={14} color="var(--pulse-text-muted)" />
            <h2
              style={{
                fontSize: '0.7rem',
                fontWeight: 700,
                letterSpacing: '0.1em',
                textTransform: 'uppercase',
                color: 'var(--pulse-text-muted)',
              }}
            >
              Domain Intelligence · {brief.sections.length} Sections
            </h2>
          </div>
          {brief.sections.map((section) => (
            <ErrorBoundary key={section.id} name={`section:${section.id}`}>
              <SectionCard section={section} briefingId={brief.id} onFileDissent={handleFileDissent} />
            </ErrorBoundary>
          ))}
        </div>

        <HeliosFrontierBriefing />

        {/* Brief footer */}
        <div
          style={{
            padding: '14px 18px',
            borderRadius: 6,
            background: 'var(--pulse-card)',
            border: '1px solid var(--pulse-border)',
            display: 'flex',
            alignItems: 'center',
            justifyContent: 'space-between',
          }}
        >
          <div style={{ fontSize: '0.72rem', color: 'var(--pulse-text-muted)' }}>
            <strong style={{ color: 'var(--pulse-text-dim)' }}>Brief ID:</strong> {brief.id} ·
            Generated{' '}
            {new Date(brief.generatedAt).toLocaleString('en-US', {
              dateStyle: 'medium',
              timeStyle: 'short',
            })}{' '}
            UTC · <strong style={{ color: 'var(--pulse-text-dim)' }}>Counsel</strong> Multi-Agent
            Synthesis
          </div>
          <a
            href={`${BASE}/library/${brief.id}`}
            style={{
              display: 'flex',
              alignItems: 'center',
              gap: 5,
              fontSize: '0.72rem',
              color: 'var(--pulse-text-dim)',
              textDecoration: 'none',
            }}
          >
            <ExternalLink size={12} />
            View in Library
          </a>
        </div>
      </div>
    </div>
  );
}
