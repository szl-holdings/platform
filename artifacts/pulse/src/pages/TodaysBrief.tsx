function FreshnessChip({ generatedAt }: { generatedAt: string }) {
  const now = Date.now();
  const gen = new Date(generatedAt).getTime();
  const diffMs = now - gen;
  const diffMin = Math.floor(diffMs / 60000);
  const diffHrs = Math.floor(diffMin / 60);
  let label: string;
  let dotColor: string;
  if (diffMin < 60) {
    label = `${diffMin}m ago`;
    dotColor = '#4eca8b';
  } else if (diffHrs < 6) {
    label = `${diffHrs}h ago`;
    dotColor = '#c8a84b';
  } else {
    label = `${diffHrs}h ago`;
    dotColor = '#e05050';
  }
  return (
    <div
      title={`Generated at ${new Date(generatedAt).toLocaleString()}`}
      style={{
        display: 'inline-flex',
        alignItems: 'center',
        gap: 5,
        padding: '2px 8px',
        borderRadius: 4,
        border: '1px solid var(--pulse-border)',
        background: 'rgba(255,255,255,0.03)',
        fontSize: '0.63rem',
        color: 'var(--pulse-text-muted)',
        fontFamily: 'JetBrains Mono, monospace',
      }}
    >
      <Clock size={10} />
      <span>{label}</span>
      <div style={{ width: 5, height: 5, borderRadius: '50%', background: dotColor, flexShrink: 0 }} />
    </div>
  );
}

