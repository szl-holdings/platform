#!/usr/bin/env node
/**
 * rebuild-fresh.mjs — build the platform schema on an EMPTY PostgreSQL database
 * from source, without `drizzle-kit push` (closes audit F1 / gap G2).
 *
 * Why this exists
 * ---------------
 * The drizzle journal (`lib/db/drizzle/`) cannot be replayed on an empty
 * database: historical environments were populated with `drizzle-kit push`,
 * so ~23 journal entries ALTER tables that no journal entry ever creates
 * (first failure: 0016_alloy_governance_policies -> platform_workflow_runs).
 * Applied history must not be rewritten (check-journal.mjs binds the prefix),
 * so instead this script:
 *
 *   1. Refuses unless the target database is empty (no user relations in
 *      `public`, no `drizzle` schema) AND `REBUILD_FRESH_CONFIRM` equals
 *      `current_database()`. It never touches a populated database.
 *   2. In ONE transaction: creates required extensions, applies the reviewed
 *      baseline `lib/db/baseline/0000_baseline_from_schema.sql` (generated by
 *      the pinned drizzle-kit from `src/schema`; sha256 pinned in
 *      `baseline/BASELINE.json`), then replays every journal entry statement
 *      by statement inside savepoints. A statement that fails only because
 *      the object already exists (the baseline created it) is recorded as
 *      SUBSUMED; any other failure aborts and rolls back everything unless
 *      that exact (tag, statement index, SQLSTATE) is allow-listed with a
 *      reason in `baseline/replay-allowlist.json`.
 *   3. Applies `lib/db/migrations/*.sql` (the hand-authored set) the same way,
 *      in the same transaction and under the manual-migration advisory lock.
 *   4. Records every journal entry in `drizzle.__drizzle_migrations` with the
 *      same hash/created_at drizzle-orm 0.45.2 computes, and every manual file
 *      in `public.__manual_migrations` with its sha256, so the normal
 *      `pnpm --filter @szl-holdings/db migrate` afterwards is a verified no-op
 *      (and its checksum-drift guard keeps working).
 *
 * Usage
 * -----
 *   DATABASE_URL=postgres://.../newdb REBUILD_FRESH_CONFIRM=newdb \
 *     node lib/db/scripts/rebuild-fresh.mjs [--report report.json]
 *   then: pnpm --filter @szl-holdings/db migrate   (must report nothing pending)
 *
 * This is a provisioning tool for a brand-new database. It is not a deploy
 * step and must never be pointed at an existing environment.
 */
import crypto from 'node:crypto';
import fs from 'node:fs';
import path from 'node:path';
import { fileURLToPath } from 'node:url';
import pg from 'pg';
import { loadManualMigrations, MANUAL_MIGRATION_LOCK_KEY } from './apply-manual-migrations.mjs';
import { migrationDatabaseUrl } from './migration-url.mjs';

const DB_ROOT = path.resolve(path.dirname(fileURLToPath(import.meta.url)), '..');
const sha256 = (s) => crypto.createHash('sha256').update(s).digest('hex');

// SQLSTATEs meaning "the object this statement creates/adds already exists".
export const ALREADY_EXISTS = new Set([
  '42P07', // duplicate_table (also index/sequence/view)
  '42701', // duplicate_column
  '42710', // duplicate_object (constraint, type, trigger, policy, extension)
  '42P06', // duplicate_schema
  '42723', // duplicate_function
  '42P16', // invalid_table_definition — counted ONLY for "multiple primary keys" (see classify)
]);

export function loadBaseline(root = DB_ROOT) {
  const meta = JSON.parse(fs.readFileSync(path.join(root, 'baseline/BASELINE.json'), 'utf8'));
  const sql = fs.readFileSync(path.join(root, 'baseline', meta.file), 'utf8');
  const actual = sha256(sql);
  if (actual !== meta.sha256) {
    throw new Error(`baseline sha256 mismatch: expected ${meta.sha256}, got ${actual}. Regenerate and review BASELINE.json.`);
  }
  return { meta, statements: splitStatements(sql) };
}

export function splitStatements(sql) {
  return sql.split('--> statement-breakpoint').map((s) => s.trim()).filter(Boolean);
}

/**
 * Split a SQL block into top-level statements on `;`, respecting single and
 * double quotes, dollar-quoted bodies ($$ / $tag$), line and block comments.
 * Used only when a hand-written block without drizzle breakpoints fails, so
 * the failure can be localized to one statement instead of dropping the block.
 */
export function splitTopLevel(sql) {
  const out = [];
  let buf = '';
  let i = 0;
  while (i < sql.length) {
    const ch = sql[i];
    const two = sql.slice(i, i + 2);
    if (two === '--') { const end = sql.indexOf('\n', i); const stop = end < 0 ? sql.length : end; buf += sql.slice(i, stop); i = stop; continue; }
    if (two === '/*') { const end = sql.indexOf('*/', i + 2); const stop = end < 0 ? sql.length : end + 2; buf += sql.slice(i, stop); i = stop; continue; }
    if (ch === "'" || ch === '"') {
      let j = i + 1;
      while (j < sql.length) { if (sql[j] === ch) { if (sql[j + 1] === ch) { j += 2; continue; } break; } j++; }
      buf += sql.slice(i, j + 1); i = j + 1; continue;
    }
    if (ch === '$') {
      const m = /^\$[A-Za-z_]*\$/.exec(sql.slice(i));
      if (m) { const end = sql.indexOf(m[0], i + m[0].length); const stop = end < 0 ? sql.length : end + m[0].length; buf += sql.slice(i, stop); i = stop; continue; }
    }
    if (ch === ';') { if (stripComments(buf).trim()) out.push(buf.trim()); buf = ''; i++; continue; }
    buf += ch; i++;
  }
  if (stripComments(buf).trim()) out.push(buf.trim());
  return out;
}

const stripComments = (s) => s.replace(/--[^\n]*/g, '').replace(/\/\*[\s\S]*?\*\//g, '');

export function loadJournal(root = DB_ROOT) {
  const j = JSON.parse(fs.readFileSync(path.join(root, 'drizzle/meta/_journal.json'), 'utf8'));
  return j.entries.map((e) => {
    const raw = fs.readFileSync(path.join(root, 'drizzle', `${e.tag}.sql`)).toString();
    return { tag: e.tag, when: e.when, hash: sha256(raw), statements: splitStatements(raw) };
  });
}

export function loadAllowlist(root = DB_ROOT) {
  const p = path.join(root, 'baseline/replay-allowlist.json');
  if (!fs.existsSync(p)) return new Map();
  const list = JSON.parse(fs.readFileSync(p, 'utf8')).entries ?? [];
  for (const a of list) {
    if (!a.tag || typeof a.statement !== 'string' || !a.sqlstate || !a.reason || /^TODO/i.test(a.reason)) {
      throw new Error(`replay-allowlist entry incomplete (tag, statement, sqlstate, reason required): ${JSON.stringify(a)}`);
    }
  }
  return new Map(list.map((a) => [`${a.tag}#${a.statement}#${a.sqlstate}`, a.reason]));
}

export async function assertEmptyTarget(client, confirm) {
  const { rows: [{ db }] } = await client.query('select current_database() as db');
  if (!confirm || confirm !== db) {
    throw new Error(`refusing: REBUILD_FRESH_CONFIRM must equal the target database name (${db})`);
  }
  const { rows: [{ n }] } = await client.query(`
    select count(*)::int as n from pg_class c join pg_namespace ns on ns.oid = c.relnamespace
    where ns.nspname = 'public' and c.relkind in ('r','p','v','m','S','f')`);
  const { rows: [{ d }] } = await client.query(`select count(*)::int as d from pg_namespace where nspname = 'drizzle'`);
  if (n > 0 || d > 0) {
    throw new Error(`refusing: target database ${db} is not empty (public relations=${n}, drizzle schema=${d}). rebuild-fresh only provisions new databases.`);
  }
  return db;
}

async function tryStatement(client, sql) {
  await client.query('SAVEPOINT stmt');
  try {
    await client.query(sql);
    await client.query('RELEASE SAVEPOINT stmt');
    return null;
  } catch (err) {
    await client.query('ROLLBACK TO SAVEPOINT stmt');
    return err;
  }
}

function classify(entry, tag, statement, err, allow) {
  const key = `${tag}#${statement}#${err.code}`;
  const isPkDup = err.code === '42P16' && /multiple primary keys/.test(err.message);
  if ((ALREADY_EXISTS.has(err.code) && err.code !== '42P16') || isPkDup) {
    entry.subsumed.push({ statement, sqlstate: err.code });
  } else if (allow.has(key)) {
    entry.allowlisted.push({ statement, sqlstate: err.code, reason: allow.get(key) });
  } else {
    const e2 = new Error(`journal ${tag} statement ${statement} failed with ${err.code}: ${err.message}`);
    Object.assign(e2, { code: err.code, tag, statement });
    throw e2;
  }
}

export async function rebuildFresh({ client, confirm, root = DB_ROOT, log = () => {} }) {
  const db = await assertEmptyTarget(client, confirm);
  const baseline = loadBaseline(root);
  const journal = loadJournal(root);
  const allow = loadAllowlist(root);
  const report = { database: db, baseline: baseline.meta, entries: [], counts: { applied: 0, subsumed: 0, allowlisted: 0 } };
  await client.query('BEGIN');
  try {
    // Serialize with any other migrator on this database.
    await client.query('select pg_advisory_xact_lock(hashtext($1))', ['szl:platform:rebuild-fresh']);
    await client.query('select pg_advisory_xact_lock($1::bigint)', [MANUAL_MIGRATION_LOCK_KEY]);
    for (const ext of baseline.meta.extensions) await client.query(`CREATE EXTENSION IF NOT EXISTS "${ext}"`);
    for (const s of baseline.statements) await client.query(s);
    log(`[rebuild-fresh] baseline applied (${baseline.statements.length} statements)`);
    for (const e of journal) {
      const entry = { tag: e.tag, applied: 0, subsumed: [], allowlisted: [] };
      for (let i = 0; i < e.statements.length; i++) {
        const err = await tryStatement(client, e.statements[i]);
        if (!err) { entry.applied++; continue; }
        const subs = splitTopLevel(e.statements[i]);
        if (subs.length > 1 && !ALREADY_EXISTS.has(err.code)) {
          // Multi-statement hand-written block: localize the failure per statement.
          for (let k = 0; k < subs.length; k++) {
            const subErr = await tryStatement(client, subs[k]);
            if (subErr) classify(entry, e.tag, `${i}/${k}`, subErr, allow); else entry.applied++;
          }
        } else {
          classify(entry, e.tag, String(i), err, allow);
        }
      }
      report.counts.applied += entry.applied;
      report.counts.subsumed += entry.subsumed.length;
      report.counts.allowlisted += entry.allowlisted.length;
      report.entries.push(entry);
    }
    const manual = loadManualMigrations(path.join(root, 'migrations'));
    report.manual = [];
    for (const mfile of manual) {
      const entry = { file: mfile.filename, applied: 0, subsumed: [], allowlisted: [] };
      const err = await tryStatement(client, mfile.sql);
      if (!err) entry.applied = 1;
      else {
        const subs = splitTopLevel(mfile.sql);
        for (let k = 0; k < subs.length; k++) {
          const subErr = await tryStatement(client, subs[k]);
          if (subErr) classify(entry, mfile.filename, String(k), subErr, allow); else entry.applied++;
        }
      }
      report.counts.subsumed += entry.subsumed.length;
      report.counts.allowlisted += entry.allowlisted.length;
      report.manual.push(entry);
    }
    await client.query(`CREATE TABLE IF NOT EXISTS "public"."__manual_migrations" (
      "filename" TEXT PRIMARY KEY, "checksum" TEXT NOT NULL,
      "applied_at" TIMESTAMPTZ NOT NULL DEFAULT NOW(), "applied_by" TEXT)`);
    for (const mfile of manual) {
      await client.query('INSERT INTO "public"."__manual_migrations" (filename, checksum, applied_by) VALUES ($1, $2, $3)',
        [mfile.filename, mfile.checksum, 'rebuild-fresh']);
    }
    await client.query('CREATE SCHEMA IF NOT EXISTS drizzle');
    await client.query('CREATE TABLE IF NOT EXISTS drizzle.__drizzle_migrations (id SERIAL PRIMARY KEY, hash text NOT NULL, created_at bigint)');
    for (const e of journal) {
      await client.query('INSERT INTO drizzle.__drizzle_migrations (hash, created_at) VALUES ($1, $2)', [e.hash, e.when]);
    }
    await client.query('COMMIT');
  } catch (err) {
    await client.query('ROLLBACK').catch(() => {});
    throw err;
  }
  log(`[rebuild-fresh] journal replayed: ${journal.length} entries, ${report.counts.applied} statements applied; manual: ${report.manual.length} files; ${report.counts.subsumed} statements subsumed by baseline, ${report.counts.allowlisted} allow-listed`);
  return report;
}

async function main() {
  let url;
  try { url = migrationDatabaseUrl(process.env); } catch (err) { console.error(`[rebuild-fresh] ${err.message}`); process.exit(2); }
  const reportArg = process.argv.indexOf('--report');
  const client = new pg.Client({ connectionString: url });
  await client.connect();
  try {
    const report = await rebuildFresh({ client, confirm: process.env.REBUILD_FRESH_CONFIRM, log: console.log });
    if (reportArg > 0) fs.writeFileSync(process.argv[reportArg + 1], JSON.stringify(report, null, 2));
    console.log('[rebuild-fresh] done. Next: pnpm --filter @szl-holdings/db migrate — it must report nothing pending.');
  } catch (err) {
    console.error(`[rebuild-fresh] FAILED (rolled back): ${err.message}`);
    process.exitCode = 1;
  } finally {
    await client.end();
  }
}

if (import.meta.url === `file://${process.argv[1]}`) await main();
